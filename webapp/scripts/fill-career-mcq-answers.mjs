function uniq(arr) {
  return [...new Set(arr.filter(Boolean))]
}

function applyFill(asset, fill) {
  const flags = uniq(asset.flags || [])
  const drop = [
    'key_unreadable',
    'answer_unreadable',
    'stem_unrecoverable',
    'not_on_user_photos',
    'not_in_source_pdf',
    'options_unparsed',
    'options_lack_correct_provision',
  ]
  let next = flags.filter((f) => !drop.includes(f))
  const bn = asset.language_versions?.bn
  const en = asset.language_versions?.en

  if (fill.skip) {
    next.push(fill.flag || 'stem_unrecoverable')
    asset.flags = uniq(next)
    asset.flag_note = fill.note || asset.flag_note
    asset.answer_note = fill.note || asset.answer_note
    if (fill.q && bn) {
      bn.question = fill.q
      if (en) en.question = fill.q
    }
    return { kind: 'skip' }
  }

  if (fill.keep) {
    if (fill.flag) next.push(fill.flag)
    if (fill.e && bn) {
      bn.explanation = fill.e
      if (en) en.explanation = fill.e
    }
    asset.flags = uniq(next)
    if (fill.note) {
      asset.answer_note = fill.note
      asset.flag_note = [asset.flag_note, fill.note].filter(Boolean).join(' | ')
    }
    return { kind: 'keep', key: asset.correct_answer }
  }

  if (fill.noneOfPrinted) {
    if (fill.q && bn) {
      bn.question = fill.q
      if (en) en.question = fill.q
    }
    if (fill.opts && bn) {
      bn.options = { ...bn.options, ...fill.opts }
      if (en) en.options = { ...en.options, ...fill.opts }
    }
    asset.correct_answer = fill.k || 'NONE'
    if (fill.e && bn) {
      bn.explanation = fill.e
      if (en) en.explanation = fill.e
    }
    next.push('answer_none_of_printed')
    if (fill.flag) next.push(fill.flag)
    asset.flags = uniq(next)
    if (fill.note) {
      asset.answer_note = fill.note
      asset.flag_note = fill.note
    }
    return { kind: 'fill', key: asset.correct_answer }
  }

  if (fill.q && bn) {
    bn.question = fill.q
    if (en) en.question = fill.q
  }
  if (fill.opts && bn) {
    bn.options = { ...bn.options, ...fill.opts }
    if (en) en.options = { ...en.options, ...fill.opts }
  }
  if (fill.mod) {
    asset.subject_module_id = fill.mod
    asset.module_id = fill.mod
  }
  if (fill.k) {
    asset.correct_answer = fill.k
    if (fill.e && bn) {
      bn.explanation = fill.e
      if (en) en.explanation = fill.e
    }
  }
  if (fill.override) {
    next = next.filter((f) => f !== 'answer_conflict' && f !== 'user_highlight')
    next.push('statute_override')
    asset.answer_note = fill.note || asset.answer_note
  } else {
    next.push('statute_fill')
    if (fill.note) asset.answer_note = fill.note
  }
  if (fill.flag) next.push(fill.flag)
  asset.flags = uniq(next)
  if (fill.note) asset.flag_note = [asset.flag_note, fill.note].filter(Boolean).join(' | ')
  return { kind: fill.override ? 'override' : 'fill', key: fill.k }
}

const stats = { fill: 0, override: 0, skip: 0, keep: 0, missing: [] }

for (const file of PACK_FILES) {
  const abs = join(mobileDir, file)
  const data = JSON.parse(readFileSync(abs, 'utf8'))
  let touched = 0
  for (const asset of data.assets || []) {
    const fill = FILLS[asset.content_id]
    if (!fill) continue
    const r = applyFill(asset, fill)
    stats[r.kind] = (stats[r.kind] || 0) + 1
    touched++
  }
  writeFileSync(abs, `${JSON.stringify(data, null, 2)}\n`)
  const copyName = BAR_COPIES[file]
  if (copyName) {
    const dest = join(barDir, copyName)
    if (existsSync(dest) || true) writeFileSync(dest, `${JSON.stringify(data, null, 2)}\n`)
  }
  console.log('wrote', file, 'touched', touched)
}

